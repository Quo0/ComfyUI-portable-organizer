<script setup lang="ts">
// Путь, который переносится по разделителям папок, а не режется краем.
//
// У пути вида D:\program_files\comfyui\ComfyUI_windows_portable_0.31.0.7z
// нет ни одного места переноса: пробелов внутри нет, а обратная косая
// черта местом переноса не считается. Такая строка вылезает за блок,
// и её срезает `overflow: hidden` — без многоточия и без единого признака,
// что текст продолжается. А правило по всему приложению обратное:
// путь не сокращается, по нему идут разбираться руками.
import { computed } from 'vue';

const { path } = defineProps<{ path: string }>();

/**
 * Куски пути с разделителем на конце каждого.
 *
 * Разрыв должен падать после разделителя, а не посреди имени файла:
 * имя несёт версию и вариант сборки, и разорванное пополам оно
 * не читается.
 */
const parts = computed(() => path.match(/[^\\/]*[\\/]+|[^\\/]+/g) ?? []);
</script>

<template>
  <!-- `<wbr>`, а не мягкий перенос: он не добавляет в текст ни одного
       символа, и путь копируется из интерфейса целым. `&shy;` оставил бы
       в буфере дефисы, а по этим путям ходят в проводник.

       Куски раскладываются `v-for`, а не подставляются через `v-html`:
       строка приходит из файловой системы, и делать из неё разметку
       незачем. -->
  <span class="path-text"
    ><template v-for="(part, i) in parts" :key="i">{{ part }}<wbr /></template
  ></span>
</template>

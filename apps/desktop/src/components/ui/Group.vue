<script setup lang="ts">
// Блок «заголовок + контент»: подпись, форма или список, необязательная
// подсказка внизу — везде одна и та же раскладка, колонка с одинаковым
// отступом между всеми детьми. Заголовка и подвала как отдельных слотов
// нет намеренно: в разметке это просто первый и последний ребёнок,
// сам `.group` их не различает — CSS не выделяет для них отдельную
// область, в отличие от `Pane`, где шапка и подвал реально обособлены
// рамкой.
withDefaults(defineProps<{
  /** Опасная зона: отступ сверху и разделительная линия, отделяющие
   *  необратимое действие от остального содержимого экрана. */
  danger?: boolean;
}>(), { danger: false });
</script>

<template>
  <var class="Group">
    <div class="group" :class="{ 'danger-zone': danger }">
      <slot />
    </div>
  </var>
</template>


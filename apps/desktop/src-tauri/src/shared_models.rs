//! Shared model storage: scanning a root and generating
//! `extra_model_paths.yaml`.
//!
//! The mechanism is a regular part of ComfyUI; our job is to generate a
//! correct file and hand it to the instance. Only what affects the code is
//! written down here.
//!
//! **Sections are built from the subfolders that actually exist in the root,
//! not from a hardcoded list of keys.** The list of categories in ComfyUI is
//! assembled at runtime and grows from version to version
//! (`folder_paths.py:24-70`), so a baked-in list would go stale with the next
//! update. The known table below is needed for exactly two things: highlighting
//! the unrecognised in the interface, and offering to create the missing
//! standard folders.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::error::AppError;

/// The marker of a file of ours. ASCII and unchanged between versions: it is
/// what decides whether `extra_model_paths.yaml` in the user's folder may be
/// overwritten silently. Recognition must not be tied to human text — that
/// gets translated and edited, and the marker has to survive both.
pub const MARKER: &str = "# cpo:generated";

/// The header of the generated file.
///
/// In English deliberately: the file lives inside someone else's ComfyUI
/// installation and will be seen in issues and in other people's guides. It is
/// not an interface string, and `t()` has nothing to do with it.
const HEADER: &str = "# cpo:generated\n\
     # Generated by ComfyUI Portable Organizer. Manual edits will be overwritten.\n";

/// The categories known to us as of ComfyUI 0.30.
///
/// The list is taken from a real build, not invented. It does **not** limit
/// generation: any subfolder of the root becomes a key. It exists to tell "the
/// user created a new category" apart from "the user made a typo in `loras`",
/// and to offer creating what is missing.
const KNOWN: [&str; 26] = [
    "audio_encoders",
    "background_removal",
    "checkpoints",
    "clip",
    "clip_vision",
    "configs",
    "controlnet",
    "detection",
    "diffusers",
    "diffusion_models",
    "embeddings",
    "frame_interpolation",
    "geometry_estimation",
    "gligen",
    "hypernetworks",
    "latent_upscale_models",
    "loras",
    "model_patches",
    "optical_flow",
    "photomaker",
    "style_models",
    "text_encoders",
    "unet",
    "upscale_models",
    "vae",
    "vae_approx",
];

/// What is offered for creation in the shared root.
///
/// The whole known set except the legacy names: a shared folder mirroring
/// ComfyUI's model tree is exactly what the user expects. Eight of them used
/// to be offered, on the reasoning "no need to create anything extra", and it
/// looked as if the app were failing to create all the folders that matter.
///
/// The legacy `unet` and `clip` are excluded: the canonical
/// `diffusion_models` and `text_encoders` cover them, and creating both pairs
/// means creating confusion.
fn suggested() -> Vec<&'static str> {
    KNOWN
        .iter()
        .copied()
        .filter(|name| !LEGACY.iter().any(|(legacy, _)| legacy == name))
        .collect()
}

/// Legacy folder names. `folder_paths.py:111-114` reduces them to the
/// canonical ones, so we hand such a folder over under the canonical key too.
/// If both lie in the root, both paths go into one key as a multi-line block.
const LEGACY: [(&str, &str); 2] = [("unet", "diffusion_models"), ("clip", "text_encoders")];

/// The key is valid for this YAML and present in the example shipped with
/// ComfyUI — that is, a user creating such a folder is not being malicious,
/// they copied the sample. Sharing custom nodes cancels the reason this
/// project exists: instances are kept apart precisely because nodes conflict
/// with each other. Excluded unconditionally and silently in the YAML, with an
/// explanation in the interface.
const BLACKLIST: [&str; 1] = ["custom_nodes"];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub enum CategoryStatus {
    /// The name matched a known category or a legacy variant of one.
    Recognized,
    /// The name is unknown. It still goes into the YAML: ComfyUI's list of
    /// categories keeps growing, and discarding the unfamiliar would mean
    /// breaking support for new versions in the name of tidiness. It is marked
    /// in the interface so that a typo like `lora` instead of `loras` catches
    /// the eye.
    Unknown,
    /// Blacklisted. Never goes into the YAML.
    Blocked,
}

#[derive(Debug, Clone, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct SharedCategory {
    /// The subfolder's name exactly as it is on disk.
    pub folder: String,
    /// The key the folder will go into the YAML under. For legacy names it
    /// differs from `folder`; for blocked ones it is `None`.
    pub key: Option<String>,
    pub status: CategoryStatus,
    pub files: u32,
    /// `f64` rather than `u64`: specta forbids exporting integers that do not
    /// fit into a JavaScript number without losing precision.
    pub size_bytes: f64,
}

#[derive(Debug, Clone, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct RootScan {
    pub path: String,
    /// The folder is absent or unavailable. Not an error: the root can be set
    /// ahead of time, and an external drive can be unplugged.
    pub available: bool,
    pub categories: Vec<SharedCategory>,
    /// Standard categories missing from the root. Offered for creation.
    pub missing: Vec<String>,
    pub total_files: u32,
    pub total_bytes: f64,
}

/// A single shared root in the settings.
#[derive(Debug, Clone, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct SharedRoot {
    pub id: String,
    pub path: String,
    pub label: String,
    pub enabled: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct SharedSettings {
    /// Only one can be created in the interface so far, but the format is laid
    /// down as an array: the "fast SSD for checkpoints, HDD for the archive"
    /// scenario will fit without a migration — YAML can do it, one section per
    /// root, and the order of roots sets the search priority.
    pub roots: Vec<SharedRoot>,
    /// Goes into `is_default`. It only governs where ComfyUI puts newly
    /// downloaded files: the paths are additive either way.
    pub make_default_target: bool,
}

impl Default for SharedSettings {
    fn default() -> Self {
        // Downloaded once, available to all: that is what this section exists
        // for.
        Self { roots: Vec::new(), make_default_target: true }
    }
}

/// How the config is delivered to an instance.

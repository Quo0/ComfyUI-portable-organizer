fn main() {
    // Иконки в зависимости сборки не попадают: `tauri_build::build()`
    // отмечает только tauri.conf.json и capabilities. Замена файлов
    // в icons/ поэтому не пересобирает ничего, и приложение запускается
    // со старой иконкой, вшитой в прошлый бинарь, — выглядит как кэш,
    // которого нет. Отмечаем папку сами.
    println!("cargo:rerun-if-changed=icons");
    tauri_build::build()
}
